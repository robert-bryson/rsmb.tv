import { expect, test, type Page } from '@playwright/test';
import { atlas, mockAtlasAssets } from './atlasTestHelpers';

test.beforeEach(async ({ page }) => {
    await page.emulateMedia({ reducedMotion: 'reduce' });
    await mockAtlasAssets(page);
});

const defaults = ['Trip', 'Motorcycle', 'Trip dates', 'Riding days', 'Miles', 'Location', 'Reports'];
const headerOrder = async (page: Page) => (await page.getByRole('table').locator('thead th').allTextContents()).map(text => text.replace(/[↑↓↕]/g, '').trim());

test('column settings hide and reorder columns, persist after reload, and restore defaults', async ({ page }) => {
    await page.goto(`${atlas}?panel=expanded&results=table`);
    const customize = page.getByRole('button', { name: 'Customize table columns', exact: true });
    await customize.click();
    const editor = page.getByRole('dialog', { name: 'Table columns', exact: true });
    await expect(editor.getByRole('checkbox', { name: 'Show Motorcycle column', exact: true })).toBeFocused();
    await expect(editor.getByRole('checkbox', { name: 'Show Trip column', exact: true })).toBeDisabled();
    await editor.getByRole('checkbox', { name: 'Show Motorcycle column', exact: true }).uncheck();
    const miles = editor.getByRole('button', { name: 'Reorder Miles column', exact: true });
    await miles.scrollIntoViewIfNeeded();
    const grip = (await miles.boundingBox())!;
    const target = (await editor.getByRole('checkbox', { name: 'Show Trip dates column', exact: true }).boundingBox())!;
    await page.mouse.move(grip.x + grip.width / 2, grip.y + grip.height / 2);
    await page.mouse.down();
    await page.mouse.move(grip.x + grip.width / 2, target.y - 2, { steps: 10 });
    await expect(miles).toHaveAttribute('aria-pressed', 'true');
    await expect.poll(() => headerOrder(page)).toEqual(['Trip', 'Miles', 'Trip dates', 'Riding days', 'Location', 'Reports']);
    await page.mouse.up();
    await expect(miles).toHaveAttribute('aria-pressed', 'false');
    await page.keyboard.press('Escape');
    await expect(customize).toBeFocused();
    await expect.poll(() => headerOrder(page)).toEqual(['Trip', 'Miles', 'Trip dates', 'Riding days', 'Location', 'Reports']);
    await page.getByRole('columnheader', { name: 'Miles', exact: false }).getByRole('button').click();
    await expect.poll(() => new URL(page.url()).searchParams.get('sort')).toBe('miles-asc');
    await page.reload();
    await expect.poll(() => headerOrder(page)).toEqual(['Trip', 'Miles', 'Trip dates', 'Riding days', 'Location', 'Reports']);
    await customize.click();
    await editor.getByRole('button', { name: 'Reset columns', exact: true }).click();
    await expect.poll(() => headerOrder(page)).toEqual(defaults);
    await editor.getByRole('button', { name: 'Close column settings', exact: true }).click();
    await expect(customize).toBeFocused();
    await page.reload();
    await expect.poll(() => headerOrder(page)).toEqual(defaults);
});

test('trip-only tables still support keyboard selection and retain columns across report navigation', async ({ page }) => {
    await page.goto(`${atlas}?panel=expanded&results=table`);
    await page.getByRole('button', { name: 'Customize table columns', exact: true }).click();
    const editor = page.getByRole('dialog', { name: 'Table columns', exact: true });
    for (const name of defaults.slice(1)) await editor.getByRole('checkbox', { name: `Show ${name} column`, exact: true }).uncheck();
    await page.keyboard.press('Escape');
    await expect.poll(() => headerOrder(page)).toEqual(['Trip']);
    const region = page.getByRole('region', { name: 'Trip comparison table', exact: true });
    expect(await region.evaluate(element => element.scrollWidth > element.clientWidth)).toBe(false);
    const title = page.getByRole('button', { name: 'Coastal test trip', exact: true });
    await title.press('Enter');
    await expect.poll(() => new URL(page.url()).searchParams.get('trip')).toBe('coastal-test');
    await expect(page.locator('[data-trip-id="coastal-test"]')).toHaveAttribute('data-selected', 'true');
    await page.getByRole('radio', { name: 'Cards', exact: true }).click();
    await page.locator('[data-trip-id="coastal-test"]').getByRole('link', { name: /Read trip report/ }).click();
    await expect(page).toHaveURL(/\/trips\/coastal-test$/);
    await page.getByRole('link', { name: /Back to map/ }).first().click();
    await page.getByRole('radio', { name: 'Table', exact: true }).click();
    await expect.poll(() => headerOrder(page)).toEqual(['Trip']);
});

test('column editor fits a narrow panel, reaches its final options, and closes on outside clicks', async ({ page }) => {
    await page.setViewportSize({ width: 320, height: 740 });
    await page.goto(`${atlas}?panel=expanded&results=table`);
    await page.addStyleTag({ content: '#atlas-trip-list::-webkit-scrollbar { width: 16px; }' });
    const customize = page.getByRole('button', { name: 'Customize table columns', exact: true });
    const region = page.getByRole('region', { name: 'Trip comparison table', exact: true });
    const before = (await customize.boundingBox())!;
    const heading = (await page.getByRole('table').locator('thead').boundingBox())!;
    expect(before.y).toBeCloseTo(heading.y, 0);
    expect(before.y + before.height).toBeLessThanOrEqual(heading.y + heading.height + 1);
    await region.evaluate(element => { element.scrollLeft = element.scrollWidth; });
    expect((await customize.boundingBox())!.x).toBeCloseTo(before.x, 0);
    await expect(customize).toBeInViewport();
    await customize.click();
    const editor = page.getByRole('dialog', { name: 'Table columns', exact: true });
    const box = (await editor.boundingBox())!;
    const list = (await page.locator('#atlas-trip-list').boundingBox())!;
    expect(box.x).toBeGreaterThanOrEqual(list.x);
    expect(box.x + box.width).toBeLessThanOrEqual(list.x + list.width);
    expect(box.y + box.height).toBeLessThanOrEqual(list.y + list.height);
    await expect(editor.getByRole('button', { name: 'Reset columns', exact: true })).toBeInViewport();
    const reports = editor.getByRole('button', { name: 'Reorder Reports column', exact: true });
    await reports.focus();
    await reports.press('Space');
    await reports.press('ArrowUp');
    await reports.press('Space');
    await expect(reports).toBeFocused();
    await editor.getByRole('checkbox', { name: 'Show Reports column', exact: true }).uncheck();
    await editor.getByRole('button', { name: 'Reset columns', exact: true }).click();
    await expect.poll(() => headerOrder(page)).toEqual(defaults);
    // The short-sheet overlay can cover the toolbar; use an exposed map target outside it.
    await page.getByTestId('trip-atlas-map').locator('canvas').click({ position: { x: 20, y: 100 } });
    await expect(editor).toHaveCount(0);
    await page.getByRole('button', { name: 'Sort trips', exact: true }).click();
    await expect(page.getByRole('group', { name: 'Sort trips', exact: true })).toBeVisible();
    await page.keyboard.press('Escape');
    expect(new URL(page.url()).searchParams.has('trip')).toBe(false);
    expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(320);
});

test('keyboard dragging keeps Trip first, announces moves, and can cancel without closing the editor', async ({ page, browserName }) => {
    await page.goto(`${atlas}?panel=expanded&results=table`);
    await page.getByRole('button', { name: 'Customize table columns', exact: true }).click();
    const editor = page.getByRole('dialog', { name: 'Table columns', exact: true });
    const miles = editor.getByRole('button', { name: 'Reorder Miles column', exact: true });
    await miles.focus();
    await miles.press('Space');
    await miles.press('Home');
    await miles.press('ArrowUp');
    await expect.poll(() => headerOrder(page)).toEqual(['Trip', 'Miles', 'Motorcycle', 'Trip dates', 'Riding days', 'Location', 'Reports']);
    await expect(editor.getByRole('status')).toHaveText('Miles, column 2 of 7.');
    await expect(miles).toBeFocused();
    await miles.press('Escape');
    await expect(editor).toBeVisible();
    await expect(miles).toBeFocused();
    await expect(miles).toHaveAttribute('aria-pressed', 'false');
    await expect.poll(() => headerOrder(page)).toEqual(defaults);
    await expect(editor.getByRole('status')).toContainText('Original order restored');
    await miles.press('Enter');
    await miles.press('End');
    await miles.press(browserName === 'webkit' && process.platform === 'darwin' ? 'Alt+Tab' : 'Tab');
    await expect(editor.getByRole('button', { name: 'Reset columns', exact: true })).toBeFocused();
    await expect(miles).toHaveAttribute('aria-pressed', 'false');
    await expect.poll(() => headerOrder(page)).toEqual([...defaults.filter(name => name !== 'Miles'), 'Miles']);
    await page.keyboard.press('Escape');
    await expect(editor).toHaveCount(0);
    await page.reload();
    await expect.poll(() => headerOrder(page)).toEqual([...defaults.filter(name => name !== 'Miles'), 'Miles']);
});

test('Escape cancels a pointer drag and releasing does not start another move', async ({ page }) => {
    await page.goto(`${atlas}?panel=expanded&results=table`);
    await page.getByRole('button', { name: 'Customize table columns', exact: true }).click();
    const editor = page.getByRole('dialog', { name: 'Table columns', exact: true });
    const grip = editor.getByRole('button', { name: 'Reorder Motorcycle column', exact: true });
    const start = (await grip.boundingBox())!;
    await page.mouse.move(start.x + start.width / 2, start.y + start.height / 2);
    await page.mouse.down();
    await page.mouse.move(start.x + start.width / 2, start.y + start.height * 2.5, { steps: 10 });
    await expect.poll(() => headerOrder(page)).not.toEqual(defaults);
    await page.keyboard.press('Escape');
    await page.mouse.up();
    await expect(editor).toBeVisible();
    await expect(grip).toHaveAttribute('aria-pressed', 'false');
    await expect.poll(() => headerOrder(page)).toEqual(defaults);
    await editor.getByRole('checkbox', { name: 'Show Motorcycle column', exact: true }).uncheck();
    await expect(editor.getByRole('checkbox', { name: 'Show Motorcycle column', exact: true })).not.toBeChecked();
});

test('touch dragging scrolls the column list, saves on drop, and restores order on cancellation', async ({ page, isMobile, browserName }) => {
    test.skip(!isMobile || browserName !== 'chromium', 'Uses Chromium touch input on a phone viewport.');
    await page.goto(`${atlas}?panel=expanded&results=table`);
    await page.getByRole('button', { name: 'Customize table columns', exact: true }).tap();
    const editor = page.getByRole('dialog', { name: 'Table columns', exact: true });
    const grip = editor.getByRole('button', { name: 'Reorder Motorcycle column', exact: true });
    const list = editor.getByRole('list');
    const touch = await page.context().newCDPSession(page);
    const start = (await grip.boundingBox())!;
    const bounds = (await list.boundingBox())!;
    const x = start.x + start.width / 2;
    await touch.send('Input.dispatchTouchEvent', { type: 'touchStart', touchPoints: [{ x, y: start.y + start.height / 2 }] });
    await touch.send('Input.dispatchTouchEvent', { type: 'touchMove', touchPoints: [{ x, y: bounds.y + bounds.height - 2 }] });
    const reordered = [...defaults.slice(0, 1), ...defaults.slice(2), 'Motorcycle'];
    await expect.poll(() => headerOrder(page)).toEqual(reordered);
    expect(await list.evaluate(element => element.scrollTop)).toBeGreaterThan(0);
    await touch.send('Input.dispatchTouchEvent', { type: 'touchEnd', touchPoints: [] });
    await expect(grip).toHaveAttribute('aria-pressed', 'false');
    const last = (await grip.boundingBox())!;
    await touch.send('Input.dispatchTouchEvent', { type: 'touchStart', touchPoints: [{ x, y: last.y + last.height / 2 }] });
    await touch.send('Input.dispatchTouchEvent', { type: 'touchMove', touchPoints: [{ x, y: bounds.y + 2 }] });
    await expect.poll(() => headerOrder(page)).not.toEqual(reordered);
    await touch.send('Input.dispatchTouchEvent', { type: 'touchCancel', touchPoints: [] });
    await expect.poll(() => headerOrder(page)).toEqual(reordered);
    await expect(grip).toHaveAttribute('aria-pressed', 'false');
    await editor.getByRole('button', { name: 'Close column settings', exact: true }).tap();
    await page.reload();
    await expect.poll(() => headerOrder(page)).toEqual(reordered);
    await touch.detach();
});

